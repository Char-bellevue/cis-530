package edu.bellevue.cis530.studentprofileservice.entity;

import java.math.BigDecimal;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * Entity that represents one row of the student_profiles table in the student_profile_db database.
 */
@Entity
@Table(name = "student_profiles")
@Data
@NoArgsConstructor
@AllArgsConstructor
public class StudentProfile {

    // The primary key, generated by the database with auto increment.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // The logical reference to the student in the Student Service; no cross-database foreign key exists.
    @NotNull
    @Column(name = "student_id", nullable = false, unique = true)
    private Long studentId;

    // The major of the student, which must not be blank.
    @NotBlank
    private String major;

    // The grade point average of the student, which must be present.
    @NotNull
    private BigDecimal gpa;

    // The optional short biography of the student.
    private String bio;
} // end StudentProfile
