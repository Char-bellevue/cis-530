package edu.bellevue.cis530.week5.entity;

import java.math.BigDecimal;

import com.fasterxml.jackson.annotation.JsonManagedReference;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.OneToOne;
import jakarta.persistence.Table;
import jakarta.validation.Valid;
import jakarta.validation.constraints.DecimalMax;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

/**
 * Entity that represents a university student and owns the one-to-one relationship to its profile.
 */
@Entity
@Table(name = "students")
public class Student {

    // The latest enrollment year that validation allows, which is the current year.
    private static final int MAX_ENROLLMENT_YEAR = 2026;

    // The primary key, generated by the database with auto increment.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // The student first name, which must be between 2 and 50 characters.
    @NotBlank(message = "First name is required.")
    @Size(min = 2, max = 50, message = "First name must be between 2 and 50 characters.")
    @Column(name = "first_name")
    private String firstName;

    // The student last name, which must be between 2 and 50 characters.
    @NotBlank(message = "Last name is required.")
    @Size(min = 2, max = 50, message = "Last name must be between 2 and 50 characters.")
    @Column(name = "last_name")
    private String lastName;

    // The student email address, which must be a valid format and unique in the table.
    @NotBlank(message = "Email is required.")
    @Email(message = "Email must be a valid email address.")
    @Column(name = "email", unique = true)
    private String email;

    // The student major, which cannot be blank.
    @NotBlank(message = "Major is required.")
    @Column(name = "major")
    private String major;

    // The student grade point average, which must be from 0.0 to 4.0.
    @NotNull(message = "GPA is required.")
    @DecimalMin(value = "0.0", message = "GPA must be at least 0.0.")
    @DecimalMax(value = "4.0", message = "GPA must be no more than 4.0.")
    @Column(name = "gpa", precision = 3, scale = 2)
    private BigDecimal gpa;

    // The year the student enrolled, which must be from 2000 to the current year.
    @NotNull(message = "Enrollment year is required.")
    @Min(value = 2000, message = "Enrollment year must be 2000 or later.")
    @Max(value = MAX_ENROLLMENT_YEAR, message = "Enrollment year cannot be in the future.")
    @Column(name = "enrollment_year")
    private Integer enrollmentYear;

    // The owning side of the one-to-one link; JSON includes it, and saves and deletes cascade to it.
    @NotNull(message = "Profile is required.")
    @Valid
    @JsonManagedReference
    @OneToOne(cascade = CascadeType.ALL, orphanRemoval = true)
    @JoinColumn(name = "profile_id")
    private StudentProfile profile;

    /**
     * Creates an empty student, which JPA and Jackson need to build objects.
     *
     * @return nothing; a new Student object is constructed.
     */
    protected Student() {
        // No work is needed because the fields start empty.
    } // end Student

    /**
     * Returns the student id.
     *
     * @return Long the student id.
     */
    public Long getId() {
        return id;
    } // end getId

    /**
     * Sets the student id.
     *
     * @param id Long the new student id.
     * @return nothing; the field is updated.
     */
    public void setId(Long id) {
        this.id = id; // Store the new value in the field.
    } // end setId

    /**
     * Returns the student first name.
     *
     * @return String the student first name.
     */
    public String getFirstName() {
        return firstName;
    } // end getFirstName

    /**
     * Sets the student first name.
     *
     * @param firstName String the new student first name.
     * @return nothing; the field is updated.
     */
    public void setFirstName(String firstName) {
        this.firstName = firstName; // Store the new value in the field.
    } // end setFirstName

    /**
     * Returns the student last name.
     *
     * @return String the student last name.
     */
    public String getLastName() {
        return lastName;
    } // end getLastName

    /**
     * Sets the student last name.
     *
     * @param lastName String the new student last name.
     * @return nothing; the field is updated.
     */
    public void setLastName(String lastName) {
        this.lastName = lastName; // Store the new value in the field.
    } // end setLastName

    /**
     * Returns the student email address.
     *
     * @return String the student email address.
     */
    public String getEmail() {
        return email;
    } // end getEmail

    /**
     * Sets the student email address.
     *
     * @param email String the new student email address.
     * @return nothing; the field is updated.
     */
    public void setEmail(String email) {
        this.email = email; // Store the new value in the field.
    } // end setEmail

    /**
     * Returns the student major.
     *
     * @return String the student major.
     */
    public String getMajor() {
        return major;
    } // end getMajor

    /**
     * Sets the student major.
     *
     * @param major String the new student major.
     * @return nothing; the field is updated.
     */
    public void setMajor(String major) {
        this.major = major; // Store the new value in the field.
    } // end setMajor

    /**
     * Returns the student grade point average.
     *
     * @return BigDecimal the student grade point average.
     */
    public BigDecimal getGpa() {
        return gpa;
    } // end getGpa

    /**
     * Sets the student grade point average.
     *
     * @param gpa BigDecimal the new student grade point average.
     * @return nothing; the field is updated.
     */
    public void setGpa(BigDecimal gpa) {
        this.gpa = gpa; // Store the new value in the field.
    } // end setGpa

    /**
     * Returns the student enrollment year.
     *
     * @return Integer the student enrollment year.
     */
    public Integer getEnrollmentYear() {
        return enrollmentYear;
    } // end getEnrollmentYear

    /**
     * Sets the student enrollment year.
     *
     * @param enrollmentYear Integer the new student enrollment year.
     * @return nothing; the field is updated.
     */
    public void setEnrollmentYear(Integer enrollmentYear) {
        this.enrollmentYear = enrollmentYear; // Store the new value in the field.
    } // end setEnrollmentYear

    /**
     * Returns the student profile.
     *
     * @return StudentProfile the student profile.
     */
    public StudentProfile getProfile() {
        return profile;
    } // end getProfile

    /**
     * Sets the student profile.
     *
     * @param profile StudentProfile the new student profile.
     * @return nothing; the field is updated.
     */
    public void setProfile(StudentProfile profile) {
        this.profile = profile; // Store the new value in the field.
    } // end setProfile
} // end Student
