package edu.bellevue.cis530.week7.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * Entity class that maps to the members table. Each row stores one login account
 * with a username, a BCrypt encrypted password, a role, and an enabled status.
 */
@Entity
@Table(name = "members")
public class Member {

    // Primary key that is generated by the database.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // Login name, which must be unique and cannot be empty.
    @Column(nullable = false, unique = true, length = 100)
    private String username;

    // BCrypt encrypted password, never a plain-text password.
    @Column(nullable = false, length = 255)
    private String password;

    // Role of the member, either ROLE_ADMIN or ROLE_USER.
    @Column(nullable = false, length = 50)
    private String role;

    // Shows whether the account is active.
    @Column(nullable = false)
    private Boolean enabled;

    /**
     * Protected no-argument constructor that JPA requires to create entity objects.
     * No parameters. The expected output is a new empty Member object.
     */
    protected Member() {
    } // end Member

    /**
     * Gets the primary key of the member.
     * No parameters.
     * @return Long, the member id.
     */
    public Long getId() {
        return id;
    } // end getId

    /**
     * Sets the primary key of the member.
     * @param id Long, the new member id.
     */
    public void setId(Long id) {
        this.id = id;
    } // end setId

    /**
     * Gets the login name of the member.
     * No parameters.
     * @return String, the username.
     */
    public String getUsername() {
        return username;
    } // end getUsername

    /**
     * Sets the login name of the member.
     * @param username String, the new username.
     */
    public void setUsername(String username) {
        this.username = username;
    } // end setUsername

    /**
     * Gets the BCrypt encrypted password of the member.
     * No parameters.
     * @return String, the encrypted password.
     */
    public String getPassword() {
        return password;
    } // end getPassword

    /**
     * Sets the BCrypt encrypted password of the member.
     * @param password String, the new encrypted password.
     */
    public void setPassword(String password) {
        this.password = password;
    } // end setPassword

    /**
     * Gets the role of the member.
     * No parameters.
     * @return String, either ROLE_ADMIN or ROLE_USER.
     */
    public String getRole() {
        return role;
    } // end getRole

    /**
     * Sets the role of the member.
     * @param role String, the new role such as ROLE_ADMIN or ROLE_USER.
     */
    public void setRole(String role) {
        this.role = role;
    } // end setRole

    /**
     * Gets the enabled status of the member.
     * No parameters.
     * @return Boolean, true when the account is active.
     */
    public Boolean getEnabled() {
        return enabled;
    } // end getEnabled

    /**
     * Sets the enabled status of the member.
     * @param enabled Boolean, true when the account should be active.
     */
    public void setEnabled(Boolean enabled) {
        this.enabled = enabled;
    } // end setEnabled
} // end Member
