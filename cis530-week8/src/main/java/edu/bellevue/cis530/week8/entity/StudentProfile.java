package edu.bellevue.cis530.week8.entity;

import com.fasterxml.jackson.annotation.JsonBackReference;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.OneToOne;
import jakarta.persistence.Table;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;

/**
 * Entity that represents the contact profile of one student and is the inverse side of the relationship.
 */
@Schema(name = "StudentProfile", description = "The contact details and emergency contact of one student.")
@Entity
@Table(name = "student_profiles")
public class StudentProfile {

    // The primary key, generated by the database with auto increment.
    @Schema(description = "Database-generated id of the profile. Leave it out when creating a student.",
            example = "1", accessMode = Schema.AccessMode.READ_ONLY)
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // The phone number, which must use the format 555-555-1234.
    @Schema(description = "The phone number in the format 555-555-1234.", example = "555-555-1234",
            pattern = "^\\d{3}-\\d{3}-\\d{4}$", requiredMode = Schema.RequiredMode.REQUIRED)
    @NotBlank(message = "Phone is required.")
    @Pattern(regexp = "^\\d{3}-\\d{3}-\\d{4}$", message = "Phone must use the format 555-555-1234.")
    @Column(name = "phone")
    private String phone;

    // The street address of the student.
    @Schema(description = "The street address of the student.", example = "100 Main Street")
    @Column(name = "address")
    private String address;

    // The city of the student.
    @Schema(description = "The city of the student.", example = "Omaha")
    @Column(name = "city")
    private String city;

    // The two-letter state code, such as NE.
    @Schema(description = "The two-letter state code.", example = "NE", minLength = 2, maxLength = 2,
            requiredMode = Schema.RequiredMode.REQUIRED)
    @NotBlank(message = "State is required.")
    @Size(min = 2, max = 2, message = "State must be exactly 2 characters.")
    @Column(name = "state", length = 2)
    private String state;

    // The zip code, which must be exactly five digits.
    @Schema(description = "The five-digit zip code.", example = "68101", pattern = "^\\d{5}$",
            requiredMode = Schema.RequiredMode.REQUIRED)
    @NotBlank(message = "Zip is required.")
    @Pattern(regexp = "^\\d{5}$", message = "Zip must be exactly 5 digits.")
    @Column(name = "zip", length = 5)
    private String zip;

    // The name of the emergency contact.
    @Schema(description = "The name of the emergency contact.", example = "Charles Babbage", requiredMode = Schema.RequiredMode.REQUIRED)
    @NotBlank(message = "Emergency contact name is required.")
    @Column(name = "emergency_contact_name")
    private String emergencyContactName;

    // The phone number of the emergency contact.
    @Schema(description = "The phone number of the emergency contact.", example = "555-555-9876", requiredMode = Schema.RequiredMode.REQUIRED)
    @NotBlank(message = "Emergency contact phone is required.")
    @Column(name = "emergency_contact_phone")
    private String emergencyContactPhone;

    // The inverse side of the one-to-one link; it is hidden from JSON to prevent infinite recursion.
    @Schema(hidden = true)
    @JsonBackReference
    @OneToOne(mappedBy = "profile")
    private Student student;

    /**
     * Creates an empty profile, which JPA and Jackson need to build objects.
     *
     * @return nothing; a new StudentProfile object is constructed.
     */
    public StudentProfile() {
        // No work is needed because the fields start empty.
    } // end StudentProfile

    /**
     * Returns the profile id.
     *
     * @return Long the profile id.
     */
    public Long getId() {
        return id;
    } // end getId

    /**
     * Sets the profile id.
     *
     * @param id Long the new profile id.
     * @return nothing; the field is updated.
     */
    public void setId(Long id) {
        this.id = id; // Store the new value in the field.
    } // end setId

    /**
     * Returns the phone number.
     *
     * @return String the phone number.
     */
    public String getPhone() {
        return phone;
    } // end getPhone

    /**
     * Sets the phone number.
     *
     * @param phone String the new phone number.
     * @return nothing; the field is updated.
     */
    public void setPhone(String phone) {
        this.phone = phone; // Store the new value in the field.
    } // end setPhone

    /**
     * Returns the street address.
     *
     * @return String the street address.
     */
    public String getAddress() {
        return address;
    } // end getAddress

    /**
     * Sets the street address.
     *
     * @param address String the new street address.
     * @return nothing; the field is updated.
     */
    public void setAddress(String address) {
        this.address = address; // Store the new value in the field.
    } // end setAddress

    /**
     * Returns the city.
     *
     * @return String the city.
     */
    public String getCity() {
        return city;
    } // end getCity

    /**
     * Sets the city.
     *
     * @param city String the new city.
     * @return nothing; the field is updated.
     */
    public void setCity(String city) {
        this.city = city; // Store the new value in the field.
    } // end setCity

    /**
     * Returns the two-letter state code.
     *
     * @return String the two-letter state code.
     */
    public String getState() {
        return state;
    } // end getState

    /**
     * Sets the two-letter state code.
     *
     * @param state String the new two-letter state code.
     * @return nothing; the field is updated.
     */
    public void setState(String state) {
        this.state = state; // Store the new value in the field.
    } // end setState

    /**
     * Returns the five-digit zip code.
     *
     * @return String the five-digit zip code.
     */
    public String getZip() {
        return zip;
    } // end getZip

    /**
     * Sets the five-digit zip code.
     *
     * @param zip String the new five-digit zip code.
     * @return nothing; the field is updated.
     */
    public void setZip(String zip) {
        this.zip = zip; // Store the new value in the field.
    } // end setZip

    /**
     * Returns the emergency contact name.
     *
     * @return String the emergency contact name.
     */
    public String getEmergencyContactName() {
        return emergencyContactName;
    } // end getEmergencyContactName

    /**
     * Sets the emergency contact name.
     *
     * @param emergencyContactName String the new emergency contact name.
     * @return nothing; the field is updated.
     */
    public void setEmergencyContactName(String emergencyContactName) {
        this.emergencyContactName = emergencyContactName; // Store the new value in the field.
    } // end setEmergencyContactName

    /**
     * Returns the emergency contact phone number.
     *
     * @return String the emergency contact phone number.
     */
    public String getEmergencyContactPhone() {
        return emergencyContactPhone;
    } // end getEmergencyContactPhone

    /**
     * Sets the emergency contact phone number.
     *
     * @param emergencyContactPhone String the new emergency contact phone number.
     * @return nothing; the field is updated.
     */
    public void setEmergencyContactPhone(String emergencyContactPhone) {
        this.emergencyContactPhone = emergencyContactPhone; // Store the new value in the field.
    } // end setEmergencyContactPhone

    /**
     * Returns the student that owns this profile.
     *
     * @return Student the student that owns this profile.
     */
    public Student getStudent() {
        return student;
    } // end getStudent

    /**
     * Sets the student that owns this profile.
     *
     * @param student Student the new student that owns this profile.
     * @return nothing; the field is updated.
     */
    public void setStudent(Student student) {
        this.student = student; // Store the new value in the field.
    } // end setStudent
} // end StudentProfile