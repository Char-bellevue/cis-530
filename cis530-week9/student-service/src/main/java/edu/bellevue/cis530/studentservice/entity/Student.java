package edu.bellevue.cis530.studentservice.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * Entity that represents one row of the students table in the student_db database.
 */
@Entity
@Table(name = "students")
@Data
@NoArgsConstructor
@AllArgsConstructor
public class Student {

    // The primary key, generated by the database with auto increment.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // The first name of the student, which must not be blank.
    @NotBlank
    @Column(name = "first_name", nullable = false)
    private String firstName;

    // The last name of the student, which must not be blank.
    @NotBlank
    @Column(name = "last_name", nullable = false)
    private String lastName;

    // The unique email address of the student, which must use a valid email format.
    @NotBlank
    @Email
    @Column(nullable = false, unique = true)
    private String email;
} // end Student
